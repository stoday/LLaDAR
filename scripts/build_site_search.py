"""Build a deterministic full-text index for the static bilingual user guide."""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def text(parts):
    return " ".join(" ".join(parts).split())


class Document(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.main = False
        self.excluded = 0
        self.heading_tag = None
        self.heading_parts = []
        self.title_parts = []
        self.in_title = False
        self.parts = []
        self.heading = ""
        self.anchor = ""
        self.heading_number = 0
        self.sections = []
        self.feed(source)
        self.flush()

    def flush(self):
        content = text(self.parts)
        if content or self.heading:
            self.sections.append({"heading": self.heading, "anchor": self.anchor, "text": content})
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag == "h1":
            self.in_title = True
        if tag == "main":
            self.main = True
        if not self.main:
            return
        if tag in {"nav", "script", "style"}:
            self.excluded += 1
        if self.excluded:
            return
        if tag in {"h2", "h3"}:
            self.flush()
            self.heading_number += 1
            self.anchor = dict(attrs).get("id") or f"doc-search-section-{self.heading_number}"
            self.heading = ""
            self.heading_tag = tag
            self.heading_parts = []

    def handle_endtag(self, tag):
        if tag == "h1":
            self.in_title = False
        if not self.main:
            return
        if tag in {"nav", "script", "style"}:
            self.excluded -= 1
        if self.excluded:
            return
        if tag == self.heading_tag:
            self.heading = text(self.heading_parts)
            self.heading_tag = None
        if tag == "main":
            self.main = False

    def handle_data(self, data):
        if self.in_title:
            self.title_parts.append(data)
            return
        if not self.main or self.excluded:
            return
        if self.heading_tag:
            self.heading_parts.append(data)
        else:
            self.parts.append(data)


def build(site):
    documents = []
    for path in sorted(site.rglob("*.html")):
        relative = path.relative_to(site).as_posix()
        page = Document(path.read_text(encoding="utf-8"))
        title = text(page.title_parts)
        if not title:
            raise ValueError(f"Searchable page has no main heading: {relative}")
        documents.append({"url": relative, "lang": "zh-TW" if relative.startswith("zh-TW/") else "en",
                          "title": title, "sections": page.sections})
    payload = json.dumps({"version": 1, "documents": documents}, ensure_ascii=False, separators=(",", ":"))
    return "// Generated by scripts/build_site_search.py; do not edit.\nwindow.LLaDARSearchIndex = " + payload.replace("<", "\\u003c") + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", type=Path, default=ROOT / "site")
    parser.add_argument("--check", action="store_true", help="Fail if the saved index needs regeneration.")
    args = parser.parse_args()
    expected = build(args.site)
    target = args.site / "assets" / "search-index.js"
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != expected:
            parser.error("Search index is stale. Run python scripts/build_site_search.py.")
    else:
        target.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Search index verified: {len(list(args.site.rglob('*.html')))} pages.")


if __name__ == "__main__":
    main()
