"""Render and save a consistent package from the host-validated plan."""

import hashlib
import json
from pathlib import Path
import traceback

from .language import current_language
from .plan_events import redact


def commands_script(plan):
    def quote(value):
        return "'" + value.replace("'", "''") + "'"

    lines = ["# Generated by lladar plan; commands have not been executed.",
             "$ErrorActionPreference = 'Stop'"]
    for argv in plan["commands"]:
        lines.extend(["& " + " ".join(quote(arg) for arg in argv),
                      "if ($LASTEXITCODE -ne 0) { throw 'LLaDAR stage failed; see its log.' }"])
    return "\n".join(lines) + "\n"


def render_plan(plan):
    zh = current_language().ui_lang == "zh-TW"
    names = (["LLaDAR 測試計畫", "狀態", "測試目標", "可觀察行為", "方法與階段", "必要資料", "受測入口", "限制", "假設", "未解問題", "診斷"] if zh else
             ["LLaDAR Test Plan", "Status", "Test goal", "Observable behavior", "Method and stages", "Inputs", "Target", "Limitations", "Assumptions", "Open questions", "Diagnostics"])
    lines = [f"# {names[0]}", "", f"{names[1]}: `{plan['status']}`", "",
             "尚未呼叫受測 Agent；下列命令尚未執行。" if zh else "The target Agent has not been called; planned commands have not been executed."]
    values = [plan.get("user_goal", ""), plan.get("observable_behavior", ""),
              {"workflow": plan.get("workflow"), "method": plan.get("method"), "evaluation": plan.get("evaluation"), "stages": plan.get("stages", [])},
              plan.get("inputs", {}), plan.get("target", {}), plan.get("limitations", []),
              plan.get("assumptions", []), plan.get("open_questions", []), plan.get("diagnostics", [])]
    labels = ({"workflow": "工作流", "method": "測試方法", "evaluation": "評估方式", "stages": "執行順序",
               "kind": "類型", "count": "題數", "instructions": "測試說明", "stop_criteria": "停止條件", "max_turns": "最多回合數",
               "num_scenarios": "情境數", "knowledge": "知識文件", "dataset": "既有題庫", "responses": "既有回答",
               "situation_config": "情境設定", "path": "路徑", "url": "網址", "api_guide": "API 文件", "service_url": "服務網址",
               "criteria": "評估判準", "skill": "評估 Skill"} if zh else {})

    def rows(value, prefix=""):
        if isinstance(value, dict):
            result = []
            for key, item in value.items():
                if item not in (None, "", [], {}):
                    label = labels.get(key, key)
                    result.extend(rows(item, f"{prefix}{label}: "))
            return result
        if isinstance(value, list):
            return [row for item in value for row in rows(item, prefix)]
        return [f"- {prefix}{value}"]

    for name, value in zip(names[2:], values):
        lines.extend(["", f"## {name}", ""])
        if isinstance(value, str):
            lines.append(value)
        elif name == names[-1]:
            for diagnostic in value:
                lines.extend([f"- `{diagnostic['code']}` ({diagnostic['stage']}, `{diagnostic.get('trace_id', '')}`): {diagnostic['message']}",
                              f"  {'下一步' if zh else 'Next action'}: {diagnostic['next_action']}"])
            if not value:
                lines.append("無" if zh else "None")
        else:
            lines.extend(rows(redact(value)) or ["無／不適用" if zh else "None / not applicable"])
    if plan["status"] == "ready":
        lines.extend(["", "## " + ("計畫指令（尚未執行）" if zh else "Planned commands (not executed)"), "",
                      "```powershell", commands_script(plan).rstrip(), "```"])
    return "\n".join(lines) + "\n"


def write_package(destination: Path, payload: dict, events):
    plan = payload["plan"]
    contents = {"plan.json": json.dumps(redact(payload), ensure_ascii=False, indent=2) + "\n",
                "plan.md": render_plan(plan)}
    if plan["status"] == "ready":
        contents["commands.ps1"] = commands_script(plan)
    if plan["status"] in {"blocked", "failed"}:
        contents["diagnostics.json"] = json.dumps(redact(plan["diagnostics"]), ensure_ascii=False, indent=2) + "\n"
    failures = []
    for filename, text in contents.items():
        path = destination / filename
        try:
            events.emit("write", "start", "Writing artifact", path=str(path))
            path.write_text(text, encoding="utf-8")
            events.emit("write", "success", "Artifact written", path=str(path), sha256=hashlib.sha256(path.read_bytes()).hexdigest())
        except OSError as error:
            from .plan_spec import PlanError
            diagnostic = PlanError("PLAN_ARTIFACT_WRITE_ERROR", f"Cannot write {path}: {error}",
                                   stage="write", field=filename, recoverable=False,
                                   next_action="Choose a new writable output directory.").diagnostic
            failures.append(events.diagnostic(diagnostic, exception_type=type(error).__name__, stack_trace=traceback.format_exc()))
    return failures
